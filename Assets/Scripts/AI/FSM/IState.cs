namespace MOBA.AI
{
    /// <summary>
    /// 有限状态机的状态契约（对应计划书 3.4）。
    ///
    /// 职责边界：
    /// 1. 本接口只定义「一个状态在被激活、被驱动、被退出时分别做什么」这三件事，
    ///    不包含任何具体行为，也不引用 MonoBehaviour —— 状态是纯逻辑对象，
    ///    由 EntityAIController 持有并驱动，不需要挂在 GameObject 上。
    /// 2. 状态实现【只编排组件能力】，例如调用 MovementComponent.MoveTo()、
    ///    CombatComponent.TryAttack()；不得自行修改生命值，也不得直接操作 NavMeshAgent。
    ///    这条约束保证「移动」与「伤害结算」各自只有一个入口，避免多处写入互相打架。
    ///
    /// 生命周期约定（由 StateMachine 保证调用顺序）：
    ///   Enter() → Tick() (每帧重复) → Exit()
    /// 任何一次状态切换都必须先对旧状态调用 Exit，再对新状态调用 Enter，
    /// 因此实现方可以安全地在 Enter/Exit 中做「成对」的资源申请与释放（例如订阅/退订事件）。
    /// </summary>
    public interface IState
    {
        /// <summary>
        /// 进入该状态时调用一次。
        /// 典型用途：重置状态内部计时器、下达一次性的移动指令（如设置目的地）、播放状态相关表现。
        /// 约定：本方法可能在同一状态被重复进入时多次调用，实现必须是幂等的，不要假设只执行一次。
        /// </summary>
        void Enter();

        /// <summary>
        /// 状态持续期间由 StateMachine 每帧调用。
        /// 典型用途：检测切换条件（距离、目标有效性、是否到达路径点）并决定是否请求切换状态。
        /// 约定：本方法每帧都会执行，内部不得做物理范围查询等昂贵操作——
        /// 按计划书「推荐实施原则」，AI 感知应采用固定周期检测而非每帧查询。
        /// </summary>
        void Tick();

        /// <summary>
        /// 离开该状态时调用一次，且在下一个状态的 Enter 之前执行。
        /// 典型用途：停止寻路（MovementComponent.Stop()）、清理内部缓存、退订事件。
        /// 约定：必须与 Enter 中申请的资源成对，否则状态切换会留下悬空引用或持续生效的副作用。
        /// </summary>
        void Exit();
    }
}
