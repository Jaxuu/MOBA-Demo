namespace MOBA.Skills
{
    /// <summary>
    /// 技能施法类型：决定"这次施法需要一个什么样的目标"。
    ///
    /// 这个枚举是技能系统的第一个分派点：SkillComponent 在释放阶段按它决定生成弹道还是生成范围场。
    /// 与 SkillEffectType（造成什么效果）刻意分开——两者是正交的两个维度，
    /// 例如「指向性 + 减速」与「非指向性 + 减速」应当是同一套效果代码、不同的施法路径。
    /// </summary>
    public enum SkillCastType
    {
        /// <summary>指向性：必须锁定一个合法的敌方单位，射程按"施法者 → 目标单位"计算。</summary>
        UnitTarget = 0,

        /// <summary>非指向性：只需要一个地面落点，射程按"施法者 → 落点"计算。</summary>
        GroundPoint = 1,

        /// <summary>
        /// 自身施法（阶段八新增）：不需要目标、不需要落点，按键即生效。
        ///
        /// 【为什么必须单列一种形态，而不是"传自己当目标"】两者在三个地方语义不同：
        ///   1. 射程校验 —— Self 技能不该有"距离太远"这条拒绝路径（施法者到自己恒为 0 米），
        ///      若复用 UnitTarget，策划一旦把 castRange 填小就会得到一个"永远放不出来"的技能；
        ///   2. 目标合法性 —— UnitTarget 的校验链要求目标是【敌方】（见 SkillComponent.TryValidateTarget），
        ///      把自己传进去会被"目标非法（不是敌方单位）"拒绝；
        ///   3. 效果载体分派 —— Self 技能若配了持续时长，要在【施法者脚下】生成一个跟随自身的范围场
        ///      （见 AreaEffectZone.followCaster），而不是在某个落点生成。
        /// 把形态写成数据，上面三处分派就都只有一条 if，不需要在任何一层猜"这次施法想干嘛"。
        ///
        /// 【显式赋值 2 的原因】SkillComponent 与若干编辑器工具按 (int)castType 落盘/读取，
        /// 值必须稳定；中间插入成员会让已存在的技能资产被整体重新解释（且不报任何错）。
        /// </summary>
        Self = 2,
    }
}
